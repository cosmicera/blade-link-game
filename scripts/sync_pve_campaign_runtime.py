#!/usr/bin/env python3
"""Export the campaign specification as browser data without mixing it into PvP."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SET_DIR = ROOT / "pve-cave-test-v1"
SOURCE = SET_DIR / "campaign-v1.json"
DESTINATION = ROOT / "pve-campaign-data.js"


def main() -> None:
    campaign = json.loads(SOURCE.read_text(encoding="utf-8"))
    for card in campaign["cards"]["leaders"]:
        card["image"] = "pve-cave-test-v1/" + card["image"]
    for card in [*campaign["cards"]["followers"], *campaign["cards"]["effects"]]:
        filename = card.get("image") or f"images/campaign_cards/{card['id']}.png"
        card["image"] = "pve-cave-test-v1/" + filename
        if card["type"] == "unit":
            card.setdefault("role", "층별 토착 생물" if card.get("pool") == "floor_exclusive" else "공통 생태권 생물")
            card.setdefault("position", card["role"])
    output = json.dumps(campaign, ensure_ascii=False, separators=(",", ":"))
    source = f'''/* Generated by scripts/sync_pve_campaign_runtime.py. Keep PvE cards out of the PvP deck pool. */
(() => {{
  const campaign = {output};
  window.PVE_CAMPAIGN = campaign;
  window.GAME_DATA.factions.cave = {{
    id: 'cave', name: '스타룬데르 토착 생물', short: 'DEEP CAVE', badge: 'PVE',
    color: '#9ccab7', accent: '#d9f0df', logo: '◇', district: '심층 탐사 구역',
    style: '행성의 지하 생태권을 지키는 토착 생물', leader: campaign.cards.leaders[0].id
  }};
  window.GAME_DATA.pveCards = [...campaign.cards.followers, ...campaign.cards.effects];
  campaign.cards.leaders.forEach(card => {{
    window.GAME_DATA.leaders[card.id] = {{
      id: card.id, faction: 'cave', name: card.name, epithet: card.role,
      ability: card.floor === 10 ? '심부 공명 단계' : '굴의 공명',
      abilityText: card.abilityText, quote: card.story, story: card.story,
      image: card.image, health: card.health, maxHealth: card.maxHealth,
      pveAbility: card.ability, floor: card.floor, habitat: card.habitat, deckLimit: 1
    }};
  }});
}})();
'''
    DESTINATION.write_text(source, encoding="utf-8")
    print(f"Wrote {DESTINATION}")


if __name__ == "__main__":
    main()
